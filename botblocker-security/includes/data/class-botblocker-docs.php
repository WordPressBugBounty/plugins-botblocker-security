	// Docs language from the plugin locale; the docs site falls back to English for untranslated pages.
	public static function lang(): string {
		$locale = isset( $_COOKIE['bbcs_preferred_language'] )
			? sanitize_text_field( wp_unslash( $_COOKIE['bbcs_preferred_language'] ) )
			: determine_locale();
		$code = strtolower( substr( (string) preg_replace( '/[-_].*/', '', $locale ), 0, 2 ) );

		return in_array( $code, self::LANGS, true ) ? $code : 'en';
	}

	public static function page( string $page, string $heading = '' ): string {
		if ( $page === '' ) {
			return '';
		}

		$url = self::BASE . self::lang() . '/' . $page;

		if ( $heading !== '' ) {
			$url .= '?id=' . rawurlencode( $heading );
		}

		return $url;
	}

	public static function url( string $key ): string {
		$page = isset( self::$settings[ $key ] ) ? self::$settings[ $key ] : '';

		if ( $page === '' ) {
			return '';
		}

		return self::page( $page, 'setting-' . $key );
	}
