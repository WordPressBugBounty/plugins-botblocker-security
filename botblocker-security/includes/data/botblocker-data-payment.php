function bbcs_payment_detect_ecommerce(): bool {
    foreach ( bbcs_get_ecommerce_plugin_classes() as $class ) {
        if ( class_exists( $class ) ) {
            return true;
        }
    }
    foreach ( bbcs_get_ecommerce_plugin_constants() as $const ) {
        if ( defined( $const ) ) {
            return true;
        }
    }
    if ( function_exists( 'is_plugin_active' ) ) {
        $slugs = [
            'woocommerce/woocommerce.php',
            'easy-digital-downloads/easy-digital-downloads.php',
            'easy-digital-downloads-pro/easy-digital-downloads.php',
            'wp-e-commerce/wp-shopping-cart.php',
            'jigoshop/jigoshop.php',
            'shopp/Shopp.php',
            'give/give.php',
            'memberpress/memberpress.php',
            'restrict-content-pro/restrict-content-pro.php',
            'paid-memberships-pro/paid-memberships-pro.php',
            'woocommerce-subscriptions/woocommerce-subscriptions.php',
            'surecart/surecart.php',
            'wpeasycart/wpeasycart.php',
            'ecwid-shopping-cart/ecwid-shopping-cart.php',
            'invoicing/invoicing.php',
            'wp-invoicing/wp-invoicing.php',
            'cart66-cloud/cart66-cloud.php',
            'dokan-lite/dokan.php',
            'wc-vendors/class-wc-vendors.php',
            'wc-frontend-manager/wc_frontend_manager.php',
            'cartflows/cartflows.php',
            'funnel-builder/funnel-builder.php',
        ];
        foreach ( $slugs as $slug ) {
            if ( is_plugin_active( $slug ) ) {
                return true;
            }
        }
    }
    return false;
}
