	public static function detectEcommerce(): bool {
		foreach ( self::getEcommercePluginClasses() as $class ) {
			if ( class_exists( $class ) ) {
				return true;
			}
		}
		foreach ( self::getEcommercePluginConstants() as $const ) {
			if ( defined( $const ) ) {
				return true;
			}
